#!/usr/bin/env python3
"""Generates src/tokenizer/nfc_tables.h: canonical decompositions, canonical combining classes
and primary composites, enough to implement NFC normalization (needed by the Qwen2 tokenizer).

  /opt/homebrew/bin/python3.12 tests/reference/gen_nfc_tables.py
"""

import unicodedata
from pathlib import Path

OUT = Path(__file__).parent.parent.parent / "src" / "tokenizer" / "nfc_tables.h"


def main():
    decomps = []      # (cp, first, second)  canonical decompositions (non-Hangul)
    compositions = []  # (first, second, composite)
    ccc_ranges = []
    start = None
    prev_ccc = 0
    for cp in range(0x110000):
        ch = chr(cp)
        ccc = unicodedata.combining(ch)
        if ccc != prev_ccc or (ccc != 0 and start is None):
            if start is not None and prev_ccc != 0:
                ccc_ranges.append((start, cp - 1, prev_ccc))
            start = cp if ccc != 0 else None
            prev_ccc = ccc
        d = unicodedata.decomposition(ch)
        if d and not d.startswith("<") and not (0xAC00 <= cp <= 0xD7A3):
            parts = [int(x, 16) for x in d.split()]
            assert 1 <= len(parts) <= 2, (cp, d)
            first = parts[0]
            second = parts[1] if len(parts) == 2 else 0
            decomps.append((cp, first, second))
            # Primary composite: two-element decomposition, not excluded (NFC keeps it composed).
            if len(parts) == 2 and unicodedata.normalize("NFC", ch) == ch:
                compositions.append((first, second, cp))
    compositions.sort()

    def rows(items, fmt, per=4):
        out = []
        for i in range(0, len(items), per):
            out.append("    " + ", ".join(fmt(x) for x in items[i:i + per]) + ",")
        return "\n".join(out)

    text = f"""#pragma once

// Generated by tests/reference/gen_nfc_tables.py from Python's unicodedata
// (Unicode {unicodedata.unidata_version}). Do not edit by hand.

#include <cstdint>

namespace axon::nfc_tables {{

struct Decomposition {{
  std::uint32_t code_point;
  std::uint32_t first;
  std::uint32_t second;  // 0 for a singleton decomposition
}};

struct CombiningClassRange {{
  std::uint32_t first;
  std::uint32_t last;
  std::uint8_t ccc;
}};

struct Composition {{
  std::uint32_t first;
  std::uint32_t second;
  std::uint32_t composite;
}};

// Canonical decompositions, sorted by code point ({len(decomps)} entries). Hangul is algorithmic.
inline constexpr Decomposition kDecompositions[] = {{
{rows(decomps, lambda x: f"{{0x{x[0]:X}, 0x{x[1]:X}, 0x{x[2]:X}}}")}
}};

// Non-zero canonical combining classes ({len(ccc_ranges)} ranges).
inline constexpr CombiningClassRange kCombiningClasses[] = {{
{rows(ccc_ranges, lambda x: f"{{0x{x[0]:X}, 0x{x[1]:X}, {x[2]}}}")}
}};

// Primary composites, sorted by (first, second) ({len(compositions)} entries).
inline constexpr Composition kCompositions[] = {{
{rows(compositions, lambda x: f"{{0x{x[0]:X}, 0x{x[1]:X}, 0x{x[2]:X}}}")}
}};

}}  // namespace axon::nfc_tables
"""
    OUT.write_text(text)
    print(f"{OUT}: {len(decomps)} decompositions, {len(ccc_ranges)} ccc ranges, {len(compositions)} compositions")


if __name__ == "__main__":
    main()
