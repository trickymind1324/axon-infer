#!/usr/bin/env python3
"""Generates src/tokenizer/unicode_tables.h: code point ranges for the character classes the
pre-tokenizer needs (\\p{L}, \\p{N}, \\s as the White_Space property).

Run with the newest Python available so the tables carry a recent Unicode version:
  /opt/homebrew/bin/python3.12 tests/reference/gen_unicode_tables.py
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).parent.parent.parent / "src" / "tokenizer" / "unicode_tables.h"

LETTER = {"Lu", "Ll", "Lt", "Lm", "Lo"}
NUMBER = {"Nd", "Nl", "No"}
# The Unicode White_Space property (what \s matches in Oniguruma and the regex crate).
WHITE_SPACE = [(0x09, 0x0D), (0x20, 0x20), (0x85, 0x85), (0xA0, 0xA0), (0x1680, 0x1680),
               (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F),
               (0x3000, 0x3000)]


def ranges(predicate):
    out = []
    start = None
    for cp in range(0x110000):
        if predicate(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    lines = [f"inline constexpr CodePointRange {name}[] = {{"]
    for i in range(0, len(rs), 4):
        chunk = ", ".join(f"{{0x{a:X}, 0x{b:X}}}" for a, b in rs[i:i + 4])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    letters = ranges(lambda cp: unicodedata.category(chr(cp)) in LETTER)
    numbers = ranges(lambda cp: unicodedata.category(chr(cp)) in NUMBER)
    text = f"""#pragma once

// Generated by tests/reference/gen_unicode_tables.py from Python's unicodedata
// (Unicode {unicodedata.unidata_version}). Do not edit by hand.

#include <cstdint>

namespace axon::unicode_tables {{

struct CodePointRange {{
  std::uint32_t first;
  std::uint32_t last;
}};

inline constexpr const char* kUnicodeVersion = "{unicodedata.unidata_version}";

// General categories Lu, Ll, Lt, Lm, Lo ({len(letters)} ranges).
{emit("kLetters", letters)}

// General categories Nd, Nl, No ({len(numbers)} ranges).
{emit("kNumbers", numbers)}

// The White_Space property ({len(WHITE_SPACE)} ranges).
{emit("kWhiteSpace", WHITE_SPACE)}

}}  // namespace axon::unicode_tables
"""
    OUT.write_text(text)
    print(f"{OUT}: {len(letters)} letter ranges, {len(numbers)} number ranges, Unicode {unicodedata.unidata_version}")


if __name__ == "__main__":
    main()
